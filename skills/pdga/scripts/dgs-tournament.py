def _extract_forms(html):
    """Extract all <form> elements from HTML with their inputs."""
    forms = []
    # Find each form block
    for form_match in re.finditer(r'<form([^>]*)>(.*?)</form>', html, re.S | re.I):
        form_attrs = form_match.group(1)
        form_body = form_match.group(2)

        # Extract form attributes
        action = ""
        method = "GET"
        enctype = ""
        action_match = re.search(r'action=["\']([^"\']*)["\']', form_attrs, re.I)
        if action_match:
            action = action_match.group(1)
        method_match = re.search(r'method=["\']([^"\']*)["\']', form_attrs, re.I)
        if method_match:
            method = method_match.group(1).upper()
        enc_match = re.search(r'enctype=["\']([^"\']*)["\']', form_attrs, re.I)
        if enc_match:
            enctype = enc_match.group(1)

        # Find form ID and class
        id_match = re.search(r'id=["\']([^"\']*)["\']', form_attrs, re.I)
        class_match = re.search(r'class=["\']([^"\']*)["\']', form_attrs, re.I)

        # Extract all inputs
        inputs = []
        for inp_match in re.finditer(r'<(?:input|textarea|select)([^>]*)(?:>([^<]*)</(?:textarea|select)>|/?>)', form_body, re.S | re.I):
            inp_attrs = inp_match.group(1)
            inp_value_body = inp_match.group(2) or ""

            inp = {}
            for attr in ["name", "type", "value", "id", "class", "placeholder", "accept"]:
                attr_match = re.search(rf'{attr}=["\']([^"\']*)["\']', inp_attrs, re.I)
                if attr_match:
                    inp[attr] = attr_match.group(1)

            # Check for required, checked, selected
            if re.search(r'\brequired\b', inp_attrs, re.I):
                inp["required"] = True
            if re.search(r'\bchecked\b', inp_attrs, re.I):
                inp["checked"] = True

            # For textareas, capture the body content
            if inp_value_body.strip():
                inp["current_value"] = inp_value_body.strip()[:200]

            if inp.get("name"):
                inputs.append(inp)

        forms.append({
            "action": action,
            "method": method,
            "enctype": enctype,
            "id": id_match.group(1) if id_match else "",
            "class": class_match.group(1) if class_match else "",
            "inputs": inputs,
        })

    return forms


def _extract_meta_info(html):
    """Extract page title and any CSRF meta tags."""
    info = {}
    title_match = re.search(r'<title>([^<]+)</title>', html, re.I)
    if title_match:
        info["page_title"] = title_match.group(1).strip()

    # Look for CSRF tokens in meta tags
    for meta_match in re.finditer(r'<meta[^>]+name=["\']([^"\']*csrf[^"\']*)["\'][^>]+content=["\']([^"\']*)["\']', html, re.I):
        info[f"meta_{meta_match.group(1)}"] = meta_match.group(2)

    return info


