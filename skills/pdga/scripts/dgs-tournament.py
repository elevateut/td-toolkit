def cmd_info(args):
    """Fetch public tournament info from DGS (no auth needed)."""
    slug = args.slug
    url = f"{DGS_BASE}/tournament/{slug}"

    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            html = resp.read().decode("utf-8", errors="replace")
    except urllib.error.HTTPError as e:
        _error(f"Failed to fetch tournament page: {e.code} {e.reason}")

    info = {"slug": slug, "url": url}

    # Title
    title_match = re.search(r'<title>([^<]+)</title>', html, re.I)
    if title_match:
        info["title"] = title_match.group(1).strip().split(" - DiscGolfScene")[0].strip()

    # Player count
    reg_count = re.search(r'(\d+)\s+(?:player|registrant)s?\s+registered', html, re.I)
    if reg_count:
        info["registered_count"] = int(reg_count.group(1))

    # Dates
    date_match = re.search(r'(\w+ \d{1,2},? \d{4})\s*[-–]\s*(\w+ \d{1,2},? \d{4})', html)
    if date_match:
        info["start_date"] = date_match.group(1)
        info["end_date"] = date_match.group(2)
    else:
        single_date = re.search(r'(\w+ \d{1,2},? \d{4})', html)
        if single_date:
            info["date"] = single_date.group(1)

    # Location
    loc_match = re.search(r'<[^>]+class="[^"]*location[^"]*"[^>]*>([^<]+)', html, re.I)
    if loc_match:
        info["location"] = loc_match.group(1).strip()

    # Description snippet (first paragraph in description area)
    desc_match = re.search(r'<div[^>]+class="[^"]*description[^"]*"[^>]*>(.*?)</div>', html, re.S | re.I)
    if desc_match:
        desc_html = desc_match.group(1)
        # Strip HTML tags for a plain-text snippet
        desc_text = re.sub(r'<[^>]+>', ' ', desc_html).strip()
        desc_text = re.sub(r'\s+', ' ', desc_text)
        info["description_snippet"] = desc_text[:300]

    json.dump(info, sys.stdout, indent=2)
    print()


def cmd_check_auth(args):
    """Verify that stored cookies are still valid by accessing an admin page."""
    cookies = _load_cookies()
    slug = args.slug or os.environ.get("DGS_EVENT_SLUG", "")
    if not slug:
        _error("Need a tournament slug to test auth. Pass as argument or set DGS_EVENT_SLUG.")

    manage_url = f"{DGS_BASE}/tournaments/{slug}/admin/overview"
    body, status, final_url = _get(manage_url, cookies)

    result = {
        "slug": slug,
        "manage_url": manage_url,
        "status": status,
        "final_url": final_url,
        "cookies_valid": True,
    }

    # If we got redirected to sign-in, cookies are expired
    if "sign-in" in (final_url or "").lower():
        result["cookies_valid"] = False
        result["message"] = "Cookies expired — redirected to sign-in page. Run dgs-auth.py to re-authenticate."
    elif "manage" in (final_url or "").lower() or status == 200:
        result["message"] = "Cookies are valid. Admin access confirmed."
        # Try to extract page title for confirmation
        title_match = re.search(r'<title>([^<]+)</title>', body, re.I)
        if title_match:
            result["page_title"] = title_match.group(1).strip()
    else:
        result["cookies_valid"] = False
        result["message"] = f"Unexpected response: status={status}, url={final_url}"

    json.dump(result, sys.stdout, indent=2)
    print()


def cmd_discover(args):
    """Fetch the tournament edit page and dump all form elements.

    This is the discovery tool — run this first to understand what fields
    DGS uses for tournament editing, so we can build proper update commands.
    """
    cookies = _load_cookies()
    slug = args.slug

    # Admin overview page has all the edit forms
    edit_url = f"{DGS_BASE}/tournaments/{slug}/admin/overview"
    body, status, final_url = _get(edit_url, cookies)

    if "sign-in" in (final_url or "").lower():
        _error("Cookies expired — redirected to sign-in. Run dgs-auth.py first.")

    meta = _extract_meta_info(body)
    forms = _extract_forms(body)

    result = {
        "slug": slug,
        "url": edit_url,
        "status": status,
        "final_url": final_url,
        "meta": meta,
        "form_count": len(forms),
        "forms": forms,
    }

    # Also try to find any AJAX/API endpoints referenced in scripts
    api_endpoints = []
    for match in re.finditer(r'["\'](/(?:api|ajax|tournaments)[^"\']*)["\']', body):
        endpoint = match.group(1)
        if endpoint not in api_endpoints:
            api_endpoints.append(endpoint)
    if api_endpoints:
        result["discovered_endpoints"] = api_endpoints

    json.dump(result, sys.stdout, indent=2)
    print()

    # Human-readable summary to stderr
    sys.stderr.write(f"\n--- Form Discovery: {slug} ---\n")
    sys.stderr.write(f"Page: {edit_url}\n")
    sys.stderr.write(f"Forms found: {len(forms)}\n\n")
    for i, form in enumerate(forms):
        sys.stderr.write(f"Form {i+1}: action={form['action']} method={form['method']}")
        if form["enctype"]:
            sys.stderr.write(f" enctype={form['enctype']}")
        sys.stderr.write(f" id={form['id']}\n")
        for inp in form["inputs"]:
            req = " REQUIRED" if inp.get("required") else ""
            sys.stderr.write(f"  [{inp.get('type', 'text'):10}] {inp.get('name', '?'):30}")
            if inp.get("value"):
                sys.stderr.write(f" = {inp['value'][:50]}")
            if inp.get("current_value"):
                sys.stderr.write(f" (current: {inp['current_value'][:50]}...)")
            sys.stderr.write(f"{req}\n")
        sys.stderr.write("\n")


def cmd_discover_manage(args):
    """Discover all admin pages for a tournament.

    Fetches the manage page and extracts all admin navigation links
    to map out available management endpoints.
    """
    cookies = _load_cookies()
    slug = args.slug

    manage_url = f"{DGS_BASE}/tournaments/{slug}/admin/overview"
    body, status, final_url = _get(manage_url, cookies)

    if "sign-in" in (final_url or "").lower():
        _error("Cookies expired — redirected to sign-in. Run dgs-auth.py first.")

    # Extract all links from the admin page
    links = []
    for match in re.finditer(r'href=["\']([^"\']*)["\']', body, re.I):
        href = match.group(1)
        if slug in href or "manage" in href or "admin" in href:
            if href not in links:
                links.append(href)

    # Extract navigation items with their text
    nav_items = []
    for match in re.finditer(r'<a[^>]+href=["\']([^"\']*)["\'][^>]*>([^<]+)</a>', body, re.I):
        href = match.group(1)
        text = match.group(2).strip()
        if text and (slug in href or "manage" in href):
            nav_items.append({"href": href, "text": text})

    result = {
        "slug": slug,
        "manage_url": manage_url,
        "status": status,
        "admin_links": links,
        "nav_items": nav_items,
    }

    json.dump(result, sys.stdout, indent=2)
    print()


def cmd_update_description(args):
    """Update the tournament description.

    DGS admin URL: POST /tournaments/{slug}/admin/overview
    Field: tournament[description]
    Success: 302 redirect
    """
    cookies = _load_cookies()
    slug = args.slug
    desc_file = Path(args.file)

    if not desc_file.exists():
        _error(f"Description file not found: {desc_file}")

    description = desc_file.read_text()
    admin_url = f"{DGS_BASE}/tournaments/{slug}/admin/overview"
    form_data = {"tournament[description]": description}

    if args.dry_run:
        json.dump({"dry_run": True, "url": admin_url, "description_length": len(description)}, sys.stdout, indent=2)
        print()
        return

    sys.stderr.write(f"Posting description ({len(description)} chars) to {admin_url}\n")
    resp_body, resp_status, resp_url = _post_form(admin_url, cookies, form_data, referer=admin_url)

    success = resp_status in (200, 301, 302, 303)
    result = {"slug": slug, "status": resp_status, "success": success,
              "description_length": len(description)}
    if not success:
        result["message"] = f"Unexpected status {resp_status}"
    json.dump(result, sys.stdout, indent=2)
    print()


def cmd_upload_image(args):
    """Upload a tournament logo or flyer.

    DGS has two image endpoints:
      Logo:  POST /tournaments/{slug}/admin/logo   field: tournament_graphic
      Flyer: POST /tournaments/{slug}/admin/flyer  field: flyer (jpg/gif only)

    Use --target=logo (default) or --target=flyer.
    """
    cookies = _load_cookies()
    slug = args.slug
    image_path = Path(args.file)
    target = getattr(args, "target", "logo")

    if not image_path.exists():
        _error(f"Image file not found: {image_path}")

    content_type, _ = mimetypes.guess_type(str(image_path))
    if not content_type:
        content_type = "application/octet-stream"

    image_bytes = image_path.read_bytes()

    if target == "flyer":
        upload_url = f"{DGS_BASE}/tournaments/{slug}/admin/flyer"
        field_name = "flyer"
    else:
        upload_url = f"{DGS_BASE}/tournaments/{slug}/admin/logo"
        field_name = "tournament_graphic"

    sys.stderr.write(f"Uploading {image_path.name} ({len(image_bytes)} bytes) as {target} to {upload_url}\n")

    if args.dry_run:
        json.dump({"dry_run": True, "url": upload_url, "field": field_name,
                    "filename": image_path.name, "file_size": len(image_bytes)}, sys.stdout, indent=2)
        print()
        return

    files = [(field_name, image_path.name, image_bytes, content_type)]
    resp_body, resp_status, resp_url = _post_multipart(upload_url, cookies, {}, files, referer=upload_url)

    success = resp_status in (200, 301, 302, 303)
    result = {"slug": slug, "target": target, "status": resp_status, "success": success,
              "filename": image_path.name, "file_size": len(image_bytes)}
    if not success:
        result["message"] = f"Unexpected status {resp_status}"
    json.dump(result, sys.stdout, indent=2)
    print()


# ---------- Date Parsing Helpers ----------

def _parse_date(date_str):
    """Parse 'MM/DD/YYYY' into (month, day, year) zero-padded strings."""
    parts = date_str.strip().split("/")
    if len(parts) != 3:
        _error(f"Invalid date format '{date_str}' — expected MM/DD/YYYY")
    month, day, year = parts
    return month.zfill(2), day.zfill(2), year


def _parse_datetime(dt_str):
    """Parse 'MM/DD/YYYY H:MM AM/PM' into date + time components.

    Returns dict with keys: month, day, year, hour, minute, meridiem.
    The hour is returned in 12-hour format (01-12, with 12 for noon/midnight).
    """
    dt_str = dt_str.strip()
    # Try "MM/DD/YYYY H:MM AM" or "MM/DD/YYYY H:MM PM"
    m = re.match(
        r'(\d{1,2})/(\d{1,2})/(\d{4})\s+(\d{1,2}):(\d{2})\s*(AM|PM|am|pm)',
        dt_str
    )
    if not m:
        _error(f"Invalid datetime format '{dt_str}' — expected 'MM/DD/YYYY H:MM AM/PM'")
    month, day, year, hour, minute, meridiem = m.groups()
    # DGS uses "00" for 12 o'clock in its select options
    hour_int = int(hour)
    if hour_int == 12:
        hour = "00"
    else:
        hour = str(hour_int).zfill(2)
    return {
        "month": month.zfill(2),
        "day": day.zfill(2),
        "year": year,
        "hour": hour,
        "minute": minute.zfill(2),
        "meridiem": meridiem.lower(),
    }


