def cmd_create_discount_code(args):
    """Create a discount code.

    Best-effort implementation:
    1. GET /tournaments/{slug}/admin/new-discount-code to get AJAX fragment with a valid ID
    2. Parse the fragment for the generated code ID
    3. POST /tournaments/{slug}/admin/discount-codes with the code fields
    """
    cookies = _load_cookies()
    slug = args.slug
    codes_url = f"{DGS_BASE}/tournaments/{slug}/admin/discount-codes"
    fragment_url = f"{DGS_BASE}/tournaments/{slug}/admin/new-discount-code"

    if not args.code:
        _error("--code is required (the promo code string, e.g. 'EARLYBIRD')")

    if args.dry_run:
        result = {"dry_run": True, "url": codes_url, "fragment_url": fragment_url}
        result["code"] = args.code
        if args.amount is not None:
            result["amount"] = args.amount
        if args.percentage is not None:
            result["percentage"] = args.percentage
        if args.max_uses is not None:
            result["max_uses"] = args.max_uses
        json.dump(result, sys.stdout, indent=2)
        print()
        return

    # Step 1: GET the AJAX fragment to get a valid code ID
    sys.stderr.write(f"Fetching new discount code fragment from {fragment_url}\n")
    frag_body, frag_status, _ = _get(fragment_url, cookies)

    if frag_status != 200:
        _error(f"Failed to get discount code fragment: status {frag_status}")

    # The fragment returns JSON-escaped HTML with field names like codes[new_1234567890][code]
    # Extract the generated ID
    id_match = re.search(r'codes\[([^\]]+)\]\[code\]', frag_body)
    if not id_match:
        _error("Could not extract discount code ID from AJAX fragment. DGS may have changed their form structure.")
    code_id = id_match.group(1)
    sys.stderr.write(f"Got discount code ID: {code_id}\n")

    # Step 2: Build form data
    form_data = {
        f"codes[{code_id}][delete]": "0",
        f"codes[{code_id}][code]": args.code,
    }
    if args.amount is not None:
        form_data[f"codes[{code_id}][amount]"] = str(args.amount)
    if args.percentage is not None:
        form_data[f"codes[{code_id}][percentage]"] = str(args.percentage)
    if args.max_uses is not None:
        form_data[f"codes[{code_id}][uses]"] = str(args.max_uses)
    if args.pdga_number is not None:
        form_data[f"codes[{code_id}][pdga]"] = str(args.pdga_number)
    if args.email is not None:
        form_data[f"codes[{code_id}][email]"] = args.email

    form_data["save"] = "Save Changes"

    sys.stderr.write(f"Posting discount code '{args.code}' to {codes_url}\n")
    resp_body, resp_status, resp_url = _post_form(codes_url, cookies, form_data, referer=codes_url)

    success = resp_status in (200, 301, 302, 303)
    result = {"slug": slug, "status": resp_status, "success": success,
              "code": args.code, "code_id": code_id,
              "fields_sent": list(form_data.keys())}
    if not success:
        result["message"] = f"Unexpected status {resp_status}"
    json.dump(result, sys.stdout, indent=2)
    print()


def cmd_set_pools(args):
    """Set tournament pools.

    Best-effort: uses AJAX fragment pattern.
    1. For each pool, GET /tournaments/{slug}/pools/new to get a fragment with a valid ID
    2. POST /tournaments/{slug}/pools with all pool fields
    """
    cookies = _load_cookies()
    slug = args.slug
    pools_url = f"{DGS_BASE}/tournaments/{slug}/pools"
    new_pool_url = f"{DGS_BASE}/tournaments/{slug}/pools/new"

    if not args.pools:
        _error("No pools specified. Use --pools 'A Pool:35,B Pool:50,C Pool:20'")

    pool_entries = []
    for pair in args.pools.split(","):
        pair = pair.strip()
        if ":" in pair:
            name, cap = pair.rsplit(":", 1)
            pool_entries.append((name.strip(), cap.strip()))
        else:
            pool_entries.append((pair.strip(), ""))

    if args.dry_run:
        json.dump({"dry_run": True, "url": pools_url,
                    "pools": [{"name": n, "cap": c} for n, c in pool_entries]}, sys.stdout, indent=2)
        print()
        return

    # Fetch AJAX fragments for each pool to get valid IDs
    form_data = {}
    pool_ids = []
    for name, cap in pool_entries:
        sys.stderr.write(f"Fetching new pool fragment for '{name}'\n")
        frag_body, frag_status, _ = _get(new_pool_url, cookies)
        if frag_status != 200:
            _error(f"Failed to get pool fragment: status {frag_status}")

        id_match = re.search(r'pools\[([^\]]+)\]\[name\]', frag_body)
        if not id_match:
            _error("Could not extract pool ID from AJAX fragment.")
        pool_id = id_match.group(1)
        pool_ids.append(pool_id)

        form_data[f"pools[{pool_id}][delete]"] = "0"
        form_data[f"pools[{pool_id}][name]"] = name
        form_data[f"pools[{pool_id}][cap]"] = cap

    form_data["save"] = "Save Changes"

    sys.stderr.write(f"Posting {len(pool_entries)} pool(s) to {pools_url}\n")
    resp_body, resp_status, resp_url = _post_form(pools_url, cookies, form_data, referer=pools_url)

    success = resp_status in (200, 301, 302, 303)
    result = {"slug": slug, "status": resp_status, "success": success,
              "pools": [{"name": n, "cap": c, "id": pid}
                        for (n, c), pid in zip(pool_entries, pool_ids)],
              "fields_sent": list(form_data.keys())}
    if not success:
        result["message"] = f"Unexpected status {resp_status}"
    json.dump(result, sys.stdout, indent=2)
    print()


