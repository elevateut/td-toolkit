#!/usr/bin/env python3
"""DGS (Disc Golf Scene) tournament management script.

Manage DiscGolfScene tournaments programmatically: view info, update
overview settings, manage divisions, registration, staff, discount
codes, pools, waitlist, PDGA linking, player adds, document uploads,
and clone settings between tournaments.

Requires valid session cookies — either from ~/.dgs-cookies.json
(generated by dgs-auth.py) or from DGS_COOKIE_* env vars in .env.

Usage:
    python3 dgs-tournament.py info <slug>
    python3 dgs-tournament.py check-auth [slug]
    python3 dgs-tournament.py discover <slug>
    python3 dgs-tournament.py discover-manage <slug>
    python3 dgs-tournament.py update-description <slug> <file>
    python3 dgs-tournament.py upload-image <slug> <file> [--target logo|flyer]
    python3 dgs-tournament.py update-overview <slug> [--name ...] [--description-file ...] ...
    python3 dgs-tournament.py set-divisions <slug> --divisions "MPO:65,FPO:65" ...
    python3 dgs-tournament.py set-registration-schedule <slug> --open "07/26/2026 6:00 PM" ...
    python3 dgs-tournament.py set-registration-settings <slug> [flags]
    python3 dgs-tournament.py set-staff <slug> --staff "Name:Title:PDGA#,..."
    python3 dgs-tournament.py create-discount-code <slug> --code CODE --amount 10 ...
    python3 dgs-tournament.py set-pools <slug> --pools "A Pool:35,B Pool:50"
    python3 dgs-tournament.py set-pdga-link <slug> --pdga-id 12345 ...
    python3 dgs-tournament.py set-waitlist <slug> [flags]
    python3 dgs-tournament.py add-player <slug> --name "First Last" --division MPO ...
    python3 dgs-tournament.py upload-document <slug> <file>
    python3 dgs-tournament.py upload-pictures <slug> <file> [<file> ...]
    python3 dgs-tournament.py clone-from --source <slug> --target <slug> [--include ...]

Dependencies: Python stdlib only (no pip installs).
"""

import argparse
