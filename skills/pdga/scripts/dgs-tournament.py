def cmd_upload_pictures(args):
    """Upload one or more images to the tournament photo gallery.

    POST /tournaments/{slug}/admin/add-pictures  (multipart/form-data)
    field: pictures[] (multiple, jpeg/png), all files in one request.
    Success redirects to admin/pictures; verified by the gallery count going up.
    """
    cookies = _load_cookies()
    slug = args.slug
    files = []
    for f in args.files:
        path = Path(f)
        if not path.exists():
            _error(f"Image file not found: {path}")
        content_type, _ = mimetypes.guess_type(str(path))
        if content_type not in ("image/jpeg", "image/png"):
            _error(f"DGS gallery accepts JPEG or PNG only: {path.name}")
        files.append(("pictures[]", path.name, path.read_bytes(), content_type))

    upload_url = f"{DGS_BASE}/tournaments/{slug}/admin/add-pictures"
    before = _gallery_media(slug, cookies)

    if args.dry_run:
        json.dump({"dry_run": True, "url": upload_url, "field": "pictures[]",
                    "files": [{"filename": n, "file_size": len(b)} for _, n, b, _ in files],
                    "gallery_count": len(before)}, sys.stdout, indent=2)
        print()
        return

    sys.stderr.write(f"Uploading {len(files)} picture(s) to {upload_url}\n")
    resp_body, resp_status, resp_url = _post_multipart(upload_url, cookies, {}, files, referer=upload_url)

    after = _gallery_media(slug, cookies)
    added = [u for u in after if u not in before]
    success = resp_status in (200, 301, 302, 303) and len(added) == len(files)
    result = {"slug": slug, "status": resp_status, "success": success,
              "filenames": [n for _, n, _, _ in files],
              "gallery_before": len(before), "gallery_after": len(after), "added": added}
    if not success:
        result["message"] = f"Status {resp_status}, {len(added)} of {len(files)} new gallery images found"
    json.dump(result, sys.stdout, indent=2)
    print()


def _scrape_overview_fields(html):
    """Extract current overview field values from admin/overview HTML."""
    fields = {}
    # Extract select values (selected option)
    for m in re.finditer(
        r'name=["\']tournament\[([^\]]+)\]["\'].*?<option[^>]+selected[^>]*value=["\']([^"\']*)["\']',
        html, re.S
    ):
        fields[f"tournament[{m.group(1)}]"] = m.group(2)
    # Extract text/number/hidden input values
    for m in re.finditer(
        r'name=["\']tournament\[([^\]]+)\]["\'][^>]*value=["\']([^"\']*)["\']',
        html
    ):
        key = f"tournament[{m.group(1)}]"
        if key not in fields:
            fields[key] = m.group(2)
    # Extract textarea contents
    for m in re.finditer(
        r'name=["\']tournament\[([^\]]+)\]["\'][^>]*>(.*?)</textarea>',
        html, re.S
    ):
        fields[f"tournament[{m.group(1)}]"] = m.group(2)
    return fields


def _scrape_division_fields(html):
    """Extract currently checked divisions with fees from divisions page HTML."""
    fields = {}
    # Find all checked divisions
    for m in re.finditer(
        r'tournament\[divisions\]\[(\w+)\]\[checked\].*?value=["\']1["\'].*?checked',
        html, re.S
    ):
        code = m.group(1)
        fields[f"tournament[divisions][{code}][checked]"] = "1"
    # Find fees
    for m in re.finditer(
        r'name=["\']tournament\[divisions\]\[(\w+)\]\[fee\]["\'][^>]*value=["\']([^"\']*)["\']',
        html
    ):
        code = m.group(1)
        fields[f"tournament[divisions][{code}][fee]"] = m.group(2)
    # Find caps
    for m in re.finditer(
        r'name=["\']tournament\[(cap_total|cap_pro|cap_am)\]["\'][^>]*value=["\']([^"\']*)["\']',
        html
    ):
        fields[f"tournament[{m.group(1)}]"] = m.group(2)
    return fields


def _scrape_registration_settings(html):
    """Extract registration settings from admin/registration-settings HTML."""
    fields = {}
    # Select fields
    for m in re.finditer(
        r'name=["\']tournament\[([^\]]+)\]["\'].*?<option[^>]+selected[^>]*value=["\']([^"\']*)["\']',
        html, re.S
    ):
        fields[f"tournament[{m.group(1)}]"] = m.group(2)
    # Hidden+checkbox (checked ones have value="1" with checked attribute)
    for m in re.finditer(
        r'name=["\']tournament\[([^\]]+)\]["\'][^>]*value=["\']1["\'][^>]*checked',
        html
    ):
        fields[f"tournament[{m.group(1)}]"] = "1"
    # Text/number inputs
    for m in re.finditer(
        r'name=["\']tournament\[([^\]]+)\]["\'][^>]*value=["\']([^"\']*)["\']',
        html
    ):
        key = f"tournament[{m.group(1)}]"
        if key not in fields:
            fields[key] = m.group(2)
    return fields


def cmd_clone_from(args):
    """Clone tournament settings from one tournament to another.

    Reads overview, divisions, and/or registration settings from the source
    tournament and POSTs them to the target tournament.

    NOT a DGS endpoint — a convenience command that reads from one slug
    and writes to another.
    """
    cookies = _load_cookies()
    source = args.source
    target = args.target

    if not source or not target:
        _error("Both --source and --target are required.")

    include = set(args.include.split(",")) if args.include else {"overview", "divisions", "registration"}

    cloned = {}

    # Read and clone overview
    if "overview" in include:
        sys.stderr.write(f"Reading overview from {source}...\n")
        src_url = f"{DGS_BASE}/tournaments/{source}/admin/overview"
        body, status, _ = _get(src_url, cookies)
        if status != 200:
            _error(f"Failed to read source overview: status {status}")
        overview_fields = _scrape_overview_fields(body)
        cloned["overview"] = overview_fields

        if not args.dry_run:
            tgt_url = f"{DGS_BASE}/tournaments/{target}/admin/overview"
            sys.stderr.write(f"Writing {len(overview_fields)} overview fields to {target}...\n")
            resp_body, resp_status, _ = _post_form(tgt_url, cookies, overview_fields, referer=tgt_url)
            cloned["overview_status"] = resp_status
            cloned["overview_success"] = resp_status in (200, 301, 302, 303)

    # Read and clone divisions
    if "divisions" in include:
        sys.stderr.write(f"Reading divisions from {source}...\n")
        src_url = f"{DGS_BASE}/tournaments/{source}/divisions"
        body, status, _ = _get(src_url, cookies)
        if status != 200:
            _error(f"Failed to read source divisions: status {status}")
        div_fields = _scrape_division_fields(body)
        cloned["divisions"] = div_fields

        if not args.dry_run:
            tgt_url = f"{DGS_BASE}/tournaments/{target}/divisions"
            sys.stderr.write(f"Writing {len(div_fields)} division fields to {target}...\n")
            resp_body, resp_status, _ = _post_form(tgt_url, cookies, div_fields, referer=tgt_url)
            cloned["divisions_status"] = resp_status
            cloned["divisions_success"] = resp_status in (200, 301, 302, 303)

    # Read and clone registration settings
    if "registration" in include:
        sys.stderr.write(f"Reading registration settings from {source}...\n")
        src_url = f"{DGS_BASE}/tournaments/{source}/admin/registration-settings"
        body, status, _ = _get(src_url, cookies)
        if status != 200:
            _error(f"Failed to read source registration settings: status {status}")
        reg_fields = _scrape_registration_settings(body)
        cloned["registration"] = reg_fields

        if not args.dry_run:
            tgt_url = f"{DGS_BASE}/tournaments/{target}/admin/registration-settings"
            sys.stderr.write(f"Writing {len(reg_fields)} registration fields to {target}...\n")
            resp_body, resp_status, _ = _post_form(tgt_url, cookies, reg_fields, referer=tgt_url)
            cloned["registration_status"] = resp_status
            cloned["registration_success"] = resp_status in (200, 301, 302, 303)

    result = {
        "source": source,
        "target": target,
        "include": list(include),
        "dry_run": args.dry_run,
        "cloned": cloned,
    }
    json.dump(result, sys.stdout, indent=2)
    print()


